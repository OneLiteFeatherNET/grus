import { readFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { describe, expect, it } from 'vitest'

// Fails when app/types/grus-api.d.ts was not regenerated after api/openapi.yaml changed: run `pnpm gen:api`.
const SPEC = fileURLToPath(new URL('../../../api/openapi.yaml', import.meta.url))
const GENERATED = fileURLToPath(new URL('./grus-api.d.ts', import.meta.url))
// The banner the openapi-typescript CLI writes in front of the generated code.
const HEADER = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n'

describe('generated Grus API types', () => {
  it('match api/openapi.yaml (run pnpm gen:api)', async () => {
    const expected = HEADER + astToString(await openapiTS(pathToFileURL(SPEC)))
    const committed = await readFile(GENERATED, 'utf8')
    expect(committed, 'stale types: run pnpm gen:api').toBe(expected)
  })
})
